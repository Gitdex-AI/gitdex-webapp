const TABLES: Record<Lang, Record<Key, string>> = { en, zh };

export type T = (key: Key) => string;

export function translator(lang: Lang): T {
  return (key) => TABLES[lang][key] ?? en[key];
}

/** Looks up dynamic keys such as `status_open`, falling back to the raw value. */
export function label(t: T, prefix: string, value: string): string {
  const key = `${prefix}_${value}` as Key;
  return key in en ? t(key) : value;
}

